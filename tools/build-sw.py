#!/usr/bin/env python3
"""Regenerate sw.js: the offline cache list for every file the app needs.
Run after adding or changing app files:  python3 tools/build-sw.py
Vouchers (gitignored, private) are never listed."""
import hashlib, json, os, subprocess
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
tracked = subprocess.check_output(["git", "ls-files"], text=True).split()
skip = (".claude/", "knowledge/", "tools/", "vouchers/")
files = sorted({f for f in tracked if not f.startswith(skip) and f not in ("CLAUDE.md", "README.md", ".gitignore", "sw.js")}
               | {"index.html", "manifest.webmanifest"})
files = [f for f in files if os.path.exists(f)]
h = hashlib.sha1()
for f in files:
    h.update(f.encode()); h.update(open(f, "rb").read())
version = h.hexdigest()[:10]
open("sw.js", "w").write(f'''// Offline copy of the whole app (generated by tools/build-sw.py, do not edit by hand).
// Open the app once on good wifi before the trip; after that it works with no signal.
"use strict";
const VERSION = "ce-{version}";
const FILES = {json.dumps(["./"] + files, indent=0)};
self.addEventListener("install", (e) => {{
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
}});
self.addEventListener("activate", (e) => {{
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== VERSION).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener("fetch", (e) => {{
  if (e.request.method !== "GET" || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then((hit) => hit || fetch(e.request).then((res) => {{
    if (res.ok && !e.request.url.includes("/vouchers/")) {{ const copy = res.clone(); caches.open(VERSION).then((c) => c.put(e.request, copy)); }}
    return res;
  }}).catch(() => caches.match("./"))));
}});
''')
print(f"sw.js: {len(files)} files, version {version}")
